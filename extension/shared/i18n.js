  /** 'auto' | 'pt' | 'en' | 'es' -> 'pt' | 'en' | 'es' */
  function resolve(setting, browserLang) {
    if (SUPPORTED.includes(setting)) return setting;
    const nav = String(browserLang || (root.navigator && root.navigator.language) || 'en')
      .slice(0, 2)
      .toLowerCase();
    return SUPPORTED.includes(nav) ? nav : 'en';
  }

  function msg(key, params) {
    return params ? { key, params } : { key };
  }

  function isMsg(value) {
    return !!value && typeof value === 'object' && typeof value.key === 'string';
  }

  function t(lang, key, params) {
    const table = STRINGS[lang] || STRINGS.en;
    const p = params || {};
    let template;
    if (p.count === 1 && table[`${key}_one`] != null) template = table[`${key}_one`];
    else template = table[key] != null ? table[key] : STRINGS.en[key] != null ? STRINGS.en[key] : key;
    return String(template).replace(/\{(\w+)\}/g, (match, name) => (name in p ? render(lang, p[name]) : match));
  }

  /** Renders a message object, a plain string, or anything else, to text. */
  function render(lang, value) {
    if (value == null) return '';
    if (isMsg(value)) return t(lang, value.key, value.params);
    if (Array.isArray(value)) return value.map((v) => render(lang, v)).join(' | ');
    return String(value);
  }

  LAA.I18n = Object.freeze({ SUPPORTED, LOCALES, STRINGS, resolve, msg, isMsg, t, render });
